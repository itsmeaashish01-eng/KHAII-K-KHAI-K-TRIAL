function resetFilters() {
  state = {...state, search:'', category:'all', condition:'all', intervention:'all'};
  $('searchInput').value=''; $('categoryFilter').value='all'; $('conditionFilter').value='all'; $('interventionFilter').value='all';
  renderLibrary();
}
function renderCategoryMap() {
  const root = $('categoryMap'); root.innerHTML='';
  CATEGORY_ORDER.forEach(cat => {
    const trials = TRIALS.filter(t => t.category === cat);
    const first = trials.slice(0, 8).map(t => `<a href="#${slugify(t.name)}">${escapeHtml(t.name)}</a>`).join('');
    root.insertAdjacentHTML('beforeend', `<article class="category-card" id="map-${slugify(cat)}"><h3>${escapeHtml(cat)}</h3><p class="muted">${trials.length} trials/cards</p><div class="small-links">${first}</div><a class="btn" href="#cat-${slugify(cat)}">Open group</a></article>`);
  });
}
function getFilteredTrials() {
  return TRIALS.filter(t => {
    const hay = [t.name,t.category,t.condition,t.interventionType,t.guidelineTopic,...t.aliases].join(' ').toLowerCase();
    return (!state.search || hay.includes(state.search)) &&
      (state.category === 'all' || t.category === state.category) &&
      (state.condition === 'all' || t.condition === state.condition) &&
      (state.intervention === 'all' || t.interventionType === state.intervention);
  });
}
function renderLibrary() {
  const root = $('libraryContainer'); root.innerHTML='';
  const filtered = getFilteredTrials();
  $('resultCount').textContent = `Showing ${filtered.length} of ${TRIALS.length} trial cards. Default view shows everything.`;
  renderActiveFilters(filtered.length);
  if (!filtered.length) {
    root.innerHTML = `<div class="empty-state"><h3>No trials match those filters.</h3><p>Click <strong>Show all</strong>, or clear one filter. Example: do not combine “Thrombectomy” category with “Anticoagulation” intervention.</p><button class="btn primary" onclick="resetFilters()">Show all trials</button></div>`;
    return;
  }
  CATEGORY_ORDER.forEach(cat => {
    const group = filtered.filter(t => t.category === cat);
    if (!group.length) return;
    const cards = group.map(renderTrialCard).join('');
    root.insertAdjacentHTML('beforeend', `<section class="category-section" id="cat-${slugify(cat)}"><div class="category-heading"><h3>${escapeHtml(cat)}</h3><span class="pill">${group.length} shown</span></div><div class="trial-grid">${cards}</div></section>`);
  });
}
function renderActiveFilters(n) {
  const chips=[];
  if(state.search) chips.push(`Search: ${escapeHtml(state.search)}`);
  if(state.category !== 'all') chips.push(`Category: ${escapeHtml(state.category)}`);
  if(state.condition !== 'all') chips.push(`Condition: ${escapeHtml(state.condition)}`);
  if(state.intervention !== 'all') chips.push(`Intervention: ${escapeHtml(state.intervention)}`);
  $('activeFilters').innerHTML = chips.map(c => `<span class="filter-chip">${c}</span>`).join('') || `<span class="filter-chip">All filters cleared — ${n} cards visible</span>`;
}
