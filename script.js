function slugify(text) { return text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, ''); }
function pubmedUrl(name) { return `https://pubmed.ncbi.nlm.nih.gov/?term=${encodeURIComponent(name + ' stroke trial')}`; }
function scholarUrl(name) { return `https://scholar.google.com/scholar?q=${encodeURIComponent(name + ' stroke trial')}`; }
function guidelineSearchUrl(name) { return `https://www.google.com/search?q=${encodeURIComponent(name + ' AHA ASA stroke guideline')}`; }
function escapeHtml(str) { return String(str ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c])); }

